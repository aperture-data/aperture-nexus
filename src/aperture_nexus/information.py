def _validate_text(text: Optional[str]) -> Optional[str]:
    if text is None:
        return None
    if not isinstance(text, str):
        raise NexusValidationError(
            f"text must be a string. Got {type(text).__name__!r}."
        )
    if not text.strip():
        raise NexusValidationError("text must not be empty.")
    return text


def _validate_image(image: Optional[Any]) -> Optional[Any]:
    if image is None:
        return None

    if isinstance(image, str):
        if image.startswith(("http://", "https://")):
            return image  # URL — reachability checked at commit time
        path = Path(image)
        if not path.is_file():
            raise NexusValidationError(
                f"Image file not found: {image}. "
                "Provide a valid file path, URL, PIL Image, "
                "numpy array, or raw bytes."
            )
        return image

    if isinstance(image, bytes):
        return image

    if isinstance(image, PILImage.Image):
        return image

    if isinstance(image, np.ndarray):
        _validate_image_ndarray(image)
        return image

    raise NexusValidationError(
        f"Unsupported image type: {type(image).__name__!r}. "
        "Provide a file path, URL, bytes, PIL Image, or numpy array."
    )


def _validate_image_ndarray(arr: np.ndarray) -> None:
    if arr.ndim not in {2, 3}:
        raise NexusValidationError(
            "Image numpy array must be 2D (H, W) or 3D (H, W, C). "
            f"Got shape {arr.shape}."
        )
    if arr.ndim == 3 and arr.shape[2] not in _IMAGE_CHANNELS:
        raise NexusValidationError(
            "Image array channel count must be 1, 3, or 4. "
            f"Got shape {arr.shape}."
        )
    if arr.dtype not in _IMAGE_DTYPES:
        raise NexusValidationError(
            f"Image array dtype must be uint8 or float32. "
            f"Got {arr.dtype}."
        )


def _validate_video(video: Optional[Any]) -> Optional[Any]:
    if video is None:
        return None

    if isinstance(video, str):
        if video.startswith(("http://", "https://")):
            return video  # URL — reachability checked at commit time
        path = Path(video)
        if not path.is_file():
            raise NexusValidationError(
                f"Video file not found: {video}. "
                "Provide a valid file path, URL, or raw bytes."
            )
        return video

    if isinstance(video, bytes):
        return video

    raise NexusValidationError(
        f"Unsupported video type: {type(video).__name__!r}. "
        "Provide a file path, URL, or bytes."
    )


def _validate_blob(
    blob: Optional[Any],
    document_type: Optional[str],
) -> tuple[Optional[Any], Optional[str]]:
    if blob is None:
        if document_type is not None:
            raise NexusValidationError(
                "document_type provided but blob is None. "
                "Provide blob=<path>, blob=<url>, or blob=<bytes> "
                "alongside document_type."
            )
        return None, None

    if isinstance(blob, str):
        if blob.startswith(("http://", "https://")):
            pass  # URL — reachability checked at commit time
        else:
            path = Path(blob)
            if not path.is_file():
                raise NexusValidationError(
                    f"Blob file not found: {blob}. "
                    "Provide a valid file path, URL, or raw bytes."
                )
    elif not isinstance(blob, bytes):
        raise NexusValidationError(
            f"blob must be a file path, URL, or bytes. "
            f"Got {type(blob).__name__!r}."
        )

    if not document_type:
        raise NexusValidationError(
            "document_type is required when blob is provided. "
            'Examples: "pdf", "mp3", "docx", "csv".'
        )

    if not isinstance(document_type, str) or not document_type.strip():
        raise NexusValidationError(
            "document_type must be a non-empty string. "
            'Examples: "pdf", "mp3", "docx".'
        )

    return blob, document_type.strip().lower()


def _validate_metadata(
    metadata: Optional[dict],
) -> Optional[dict]:
    if metadata is None:
        return None
    if not isinstance(metadata, dict):
        raise NexusValidationError(
            f"metadata must be a dict. Got {type(metadata).__name__!r}."
        )
    for key, value in metadata.items():
        if not isinstance(key, str):
            raise NexusValidationError(
                f"metadata keys must be strings. Got {type(key).__name__!r}."
            )
        if key in _RESERVED_METADATA_KEYS:
            raise NexusValidationError(
                f"metadata key {key!r} is reserved by aperture-nexus. "
                f"Use the Context fields for session/user identity."
            )
        if not isinstance(value, _METADATA_VALUE_TYPES):
            raise NexusValidationError(
                f"metadata[{key!r}] has unsupported type "
                f"{type(value).__name__!r}. "
                f"Use str, int, float, or bool."
            )
    return dict(metadata)


def _validate_embedding(
    embedding: Optional[np.ndarray],
    embedding_model: Optional[str],
) -> tuple[Optional[np.ndarray], Optional[str]]:
    if embedding is None:
        return None, None

    if not isinstance(embedding, np.ndarray):
        raise NexusValidationError(
            "embedding must be a numpy array. "
            f"Got {type(embedding).__name__!r}."
        )

    if embedding.ndim != 1:
        raise NexusValidationError(
            "embedding must be a 1D array. "
            f"Got shape {embedding.shape}."
        )

    if not np.issubdtype(embedding.dtype, np.floating):
        raise NexusValidationError(
            "embedding dtype must be a float type. "
            f"Got {embedding.dtype}."
        )

    if not embedding_model:
        raise NexusValidationError(
            "embedding_model is required when embedding is provided. "
            "Provide the name of the model that produced the embedding "
            "(e.g. 'ViT-B/16', 'text-embedding-3-small')."
        )

    if not isinstance(embedding_model, str) or not embedding_model.strip():
        raise NexusValidationError(
            "embedding_model must be a non-empty string."
        )

    if any(c in embedding_model for c in ('"', "\\")):
        raise NexusValidationError(
            f"embedding_model {embedding_model!r} contains a character that is "
            "not valid in an ApertureDB DescriptorSet name. "
            'Remove double-quotes and backslashes (e.g. use "ViT-B/16" not "ViT-B\\"16").'
        )

    if any(ord(c) < 32 for c in embedding_model):
        raise NexusValidationError(
            f"embedding_model {embedding_model!r} contains a control character. "
            "Use a plain printable string (e.g. 'ViT-B/16')."
        )

    return embedding, embedding_model.strip()
